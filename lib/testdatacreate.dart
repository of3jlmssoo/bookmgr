const int daylimit = 60;

int getnext() {
  return Random().nextInt(100) >= 95 ? 1 : 0;
}

String gettitle() {
  return '${countries[Random().nextInt(countries.length - 1)]}の${nomono[Random().nextInt(nomono.length - 1)]}';
}

String getpurchaseddate(String d) {
  var dif = DateTime.now().difference(DateTime.parse(d)).inDays;
  return DateFormat('yyyy-MM-dd').format(DateTime.now().subtract(Duration(days: Random().nextInt(dif))));
}

int getpurchased() {
  return Random().nextInt(100) >= 80 ? 1 : 0;
}

String getdate() {
  return DateFormat('yyyy-MM-dd').format(DateTime.now().subtract(Duration(days: Random().nextInt(daylimit) + 1)));
}

String getgenre() {
  return BookGenre.values[Random().nextInt(BookGenre.values.length - 1)].name;
}

String getpublisher() {
  return Publisher.values[Random().nextInt(Publisher.values.length - 1)].name;
}

String getname() {
  return '${surnames[Random().nextInt(surnames.length)]}${names[Random().nextInt(names.length)]}';
}

